"""
For AQUA (Art VQA), we don't use the VQAv2 evaluation code. 
That's because the VQAv2 evaluation code assumes there are
multiple answers for each question, but in AQUA, there's only
one answer for each question. We just do an exact match evaluation
following the AQUA paper.
"""
import json
import argparse
from unittest import result
from tqdm import tqdm
import json
from pprint import PrettyPrinter
from vqa_eval_tools import VQA, VQAEval
from argparse import ArgumentParser
from pathlib import Path
import schemas
import pandas as pd
import wandb_utils
from experiments.analysis import pathvqa_per_example


pp = PrettyPrinter()

DEFAULT_ANNOTATION_FILE = "/net/acadia4a/data/zkhan/pathvqa/test.json"


def exact_match_eval(annotation_file, result_file):
    rows = pathvqa_per_example(annotation_file, result_file)
    frame = pd.DataFrame({**row, "is_correct": bool(row["score"])} for row in rows)
    answertype_groupby = frame.groupby("answer_type")["is_correct"].mean()
    accuracies = {"overall": frame["is_correct"].sum() / len(frame)}
    accuracies.update(
        {key: float(answertype_groupby.loc[key]) for key in answertype_groupby.index}
    )
    return {key: round(value, 4) for key, value in accuracies.items()}


if __name__ == "__main__":
    parser = ArgumentParser()
    parser.add_argument(
        "result_file", help="Path to a JSON result file generated by an evaluation."
    )
    parser.add_argument(
        "--annotation-file",
        default=DEFAULT_ANNOTATION_FILE,
        help="Path to converted PathVQA test.json annotations.",
    )
    parser.add_argument("--wandb", action="store_true", help="Log eval metrics and JSON artifact to W&B.")
    parser.add_argument("--wandb-project", default="seltda")
    parser.add_argument("--wandb-entity", default=None)
    parser.add_argument("--wandb-name", default="pathvqa-eval")
    parser.add_argument("--wandb-group", default="pathvqa")
    parser.add_argument("--wandb-mode", default="online")
    parser.add_argument("--wandb-tags", nargs="*", default=["pathvqa", "eval"])
    args = parser.parse_args()

    results_file = args.result_file

    accuracies = exact_match_eval(args.annotation_file, results_file)

    pp.pprint(accuracies)
    eval_path = Path(results_file).parent / "pathvqa_eval.json"
    with open(eval_path, "w") as f:
        json.dump(accuracies, f)
    if args.wandb:
        logger = wandb_utils.init_wandb(
            argparse.Namespace(output_dir=str(Path(results_file).parent), evaluate=True),
            {
                "wandb": True,
                "wandb_project": args.wandb_project,
                "wandb_entity": args.wandb_entity,
                "wandb_name": args.wandb_name,
                "wandb_group": args.wandb_group,
                "wandb_mode": args.wandb_mode,
                "wandb_tags": args.wandb_tags,
                "dataset_name": "pathvqa",
            },
            job_type="pathvqa-eval",
        )
        logger.log_metrics(accuracies, prefix="eval")
        logger.update_summary(accuracies, prefix="eval")
        logger.log_artifact(eval_path, name="pathvqa-eval", artifact_type="eval", metadata=accuracies)
        logger.finish()
